// Build-time only. data/ is the single source; no recursive public-directory copy.
import { readFile, writeFile, mkdir, lstat, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'public/shared');
const assets = ['css/base.css', 'css/layout.css', 'css/components.css', 'css/dashboard.css',
  'js/app.js', 'js/dashboardAdapters.js', 'js/dashboard.js',
  'a/fonts/inter-regular.woff2', 'a/fonts/inter-semibold.woff2',
  'a/images/hatchai-logo.webp', 'a/images/fortitle.webp'];
const html = await readFile(path.join(root, 'data/dashboard.html'), 'utf8');
const body = html.match(/<body>([\s\S]*?)<\/body>/i)?.[1];
if (!body || !body.includes('id="environmentChart"')) throw new Error('Canonical dashboard structure changed; review packaging.');
const css = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)"\s*\/>/g)].map(match => match[1]);
if (css.length !== 4 || css.some(value => !assets.includes(value.split('?')[0]))) throw new Error('Review dashboard stylesheet list.');
const fragment = '<!-- GENERATED by tools/package-online-dashboard.mjs; do not edit -->\n' +
  css.map(href => `<link rel="stylesheet" href="shared/${href}">`).join('\n') + '\n' +
  body.replace(/\s*<script\b[^>]*>[\s\S]*?<\/script>/gi, '').replace(/src="a\//g, 'src="shared/a/').trim() + '\n';
const entries = [];
await mkdir(output, { recursive: true });
if ((await lstat(output)).isSymbolicLink()) throw new Error('Refusing linked output directory.');
const allowed = new Set([...assets, 'dashboard-fragment.html', 'manifest.json']);
async function inspect(directory, prefix = '') {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = prefix + entry.name;
    if (entry.isSymbolicLink()) throw new Error('Refusing linked output.');
    if (entry.isDirectory()) await inspect(path.join(directory, entry.name), name + '/');
    else if (!allowed.has(name)) throw new Error('Unexpected output file; review before packaging.');
  }
}
await inspect(output);
// Only fixed allowlisted paths are written. Never delete existing output files.
for (const name of assets) {
  const source = path.join(root, 'data', name);
  if ((await lstat(source)).isSymbolicLink()) throw new Error('Refusing linked source.');
  const bytes = await readFile(source);
  await mkdir(path.dirname(path.join(output, name)), { recursive: true });
  await writeFile(path.join(output, name), bytes);
  entries.push({ path: name, source: 'data/' + name, sha256: createHash('sha256').update(bytes).digest('hex') });
}
await writeFile(path.join(output, 'dashboard-fragment.html'), fragment);
entries.push({ path: 'dashboard-fragment.html', source: 'data/dashboard.html', sha256: createHash('sha256').update(fragment).digest('hex') });
await writeFile(path.join(output, 'manifest.json'), JSON.stringify({ generated: 'HATCHAI shared dashboard', files: entries }, null, 2) + '\n');
console.log('Generated shared dashboard: ' + entries.length + ' files. No secrets, local configuration or control scripts included.');
